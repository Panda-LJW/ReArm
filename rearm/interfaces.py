"""All replaceable component boundaries. Implementations depend on these only."""
from __future__ import annotations

from pathlib import Path
from typing import Any, Callable, Protocol
import numpy as np
from rearm.types import (ArmState, Diagnosis, Event, FitResult, GuardReport,
                         Params, Shot, TrainingReport, TrainingSet, Version)


class ArmIO(Protocol):
    def move_to(self, q: np.ndarray, speed: float) -> None: ...
    def read_state(self) -> ArmState: ...
    def laser(self, on: bool) -> None: ...
    def observe_spot(self) -> np.ndarray | None: ...


class Geometry(Protocol):
    def predict(self, params: Params, q: np.ndarray) -> np.ndarray: ...
    def valid(self, params: Params, q: np.ndarray) -> np.ndarray: ...
    def jacobian(self, params: Params, q: np.ndarray, names: tuple[str, ...]) -> np.ndarray: ...


class ResidualModel(Protocol):
    def predict(self, feats: np.ndarray) -> tuple[np.ndarray, np.ndarray]: ...
    def fit(self, feats: np.ndarray, targets: np.ndarray) -> None: ...
    def save(self, path: str | Path) -> None: ...
    def load(self, path: str | Path) -> None: ...


class Predictor(Protocol):
    def predict(self, params: Params, q: np.ndarray, feats: np.ndarray) -> tuple[np.ndarray, np.ndarray]: ...


class VersionStore(Protocol):
    def commit(self, params: Params, residual_id: str, meta: dict) -> str: ...
    def reject(self, params: Params, meta: dict, reasons: tuple[str, ...]) -> str: ...
    def checkout(self, version_id: str, component: str = "both") -> Version: ...
    def match(self, probe: list[Shot]) -> tuple[str, float] | None: ...
    def head(self) -> Version: ...
    def list(self) -> list[Version]: ...
    def get(self, version_id: str) -> Version: ...


class EventBus(Protocol):
    def publish(self, event: Event) -> None: ...
    def subscribe(self, callback: Callable[[Event], None]) -> Callable[[], None]: ...


class ShotLog(Protocol):
    def append(self, shot: Shot) -> None: ...
    def read(self) -> list[Shot]: ...


class Fitter(Protocol):
    def fit(self, reference: Params, shots: list[Shot], free: tuple[str, ...],
            snap: bool = False) -> FitResult: ...


class Diagnostic(Protocol):
    def diagnose(self, reference: Params, shots: list[Shot]) -> Diagnosis: ...
    def next_pose(self, diagnosis: Diagnosis, pool: np.ndarray, used: np.ndarray) -> np.ndarray: ...


class Guard(Protocol):
    def check(self, old: Params, candidate: Params, holdout: list[Shot]) -> GuardReport: ...


class Detector(Protocol):
    def update(self, shot: Shot) -> bool: ...
    def reset(self) -> None: ...


class Recognizer(Protocol):
    def match(self, probes: list[Shot], versions: list[Version]) -> tuple[str, float] | None: ...


class ShotRunner(Protocol):
    def shoot(self, q: np.ndarray, version: Version, model: Predictor,
              anomalous: bool = False, role: str = "task") -> Shot: ...


class DatasetBuilder(Protocol):
    def build(self, shots: list[Shot], params: Params, version_ids: set[str]) -> TrainingSet: ...


class Trainer(Protocol):
    def train(self, data: TrainingSet, old: ResidualModel,
              candidate: ResidualModel) -> TrainingReport: ...


class IKSolver(Protocol):
    def solve(self, target: np.ndarray, params: Params, pool: np.ndarray,
              correction: Callable[[np.ndarray], np.ndarray] | None = None) -> np.ndarray: ...


class FrameSource(Protocol):
    def read(self) -> np.ndarray: ...
    def close(self) -> None: ...


class CommandController(Protocol):
    def snapshot(self) -> dict[str, Any]: ...
    def command(self, name: str, payload: dict[str, Any]) -> dict[str, Any]: ...
